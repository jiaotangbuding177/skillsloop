  async listSkills(userId: string) {
    await this.assertCurrentScopeAgentEnabled(userId);
    const response = await this.kmAgentClient.listSkills(userId);
    const allItems = this.readArray(response, "items").map((item) => ({
      id: this.readRequiredString(item, "id"),
      name: this.readRequiredString(item, "name"),
      description: this.readOptionalString(item, "description") || "",
      scope: this.readSkillScope(item),
      enabled: this.readSkillAvailabilityFlag(item, "enabled"),
      eligible: this.readSkillAvailabilityFlag(item, "eligible"),
    }));
    return {
      items: allItems.filter(
        (item) => item.eligible !== false || item.scope === ZCLAW_SCOPE_PERSONAL,
      ),
    };
  }

  /** 按默认或指定组织的 KM 实例拉取 Skill 列表（与前台 x-enterprise-id 语义一致） */
  async listSkillsInEnterpriseContext(userId: string, enterpriseId?: string | null) {
    const target = await this.enterpriseService.resolveZclawTargetForUser(
      userId,
      enterpriseId?.trim() || null,
    );
    const listed = await this.kmAgentClient.runWithTarget(target, () => this.listSkills(userId));
    const resolvedEnterpriseId = enterpriseId?.trim() || target.enterpriseId || null;
    if (!resolvedEnterpriseId) return listed;
    return {
      items: await this.filterHiddenEmergencePersonalSkills(
        userId,
        resolvedEnterpriseId,
        listed.items,
      ),
    };
  }

  /** Hide emergence drafts until the user confirms them into the personal library. */
  private async filterHiddenEmergencePersonalSkills<
    T extends { id: string; scope: string },
  >(userId: string, enterpriseId: string, items: T[]): Promise<T[]> {
    const personalIds = items
      .filter((item) => item.scope === ZCLAW_SCOPE_PERSONAL)
      .map((item) => item.id);
    if (personalIds.length === 0) return items;
    const hidden = await this.prisma.personalSkillConfig.findMany({
      where: {
        enterpriseId,
        userId,
        skillKey: { in: personalIds },
        isDeleted: false,
        isVisible: false,
      },
      select: { skillKey: true },
    });
    if (hidden.length === 0) return items;
    const hiddenKeys = new Set(hidden.map((row) => row.skillKey));
    return items.filter(
      (item) =>
        item.scope !== ZCLAW_SCOPE_PERSONAL || !hiddenKeys.has(item.id),
    );
  }

