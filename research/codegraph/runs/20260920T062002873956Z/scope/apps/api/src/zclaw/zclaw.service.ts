  /**
   * 将 managed skill 写入组织全部 active KM 实例。
   * 任一台失败即抛错（避免部分实例成功导致 DB/kmInstalled 假阳性）。
   */
  async putManagedSkillOnAllEnterpriseInstances(
    userId: string,
    skillKey: string,
    files: Array<{ path: string; content: string }>,
    enterpriseId: string,
  ): Promise<{ ok: true; successCount: number; failureCount: number; errors: string[] }> {
    const targets =
      await this.enterpriseService.listActiveOpenClawTargetsForEnterprise(enterpriseId);
    const errors: string[] = [];
    let successCount = 0;

    for (const target of targets) {
      try {
        await this.kmAgentClient.runWithTarget(target, () =>
          this.kmAgentClient.putManagedSkill(userId, skillKey, files),
        );
        successCount += 1;
      } catch (error) {
        const instanceHint = target.enterpriseOpenClawInstanceId ?? target.baseUrl;
        const message = error instanceof Error ? error.message : String(error);
        errors.push(`${instanceHint}: ${message}`);
      }
    }

    if (errors.length > 0 || successCount === 0) {
      throw new BadGatewayException(
        errors[0] || `Skill「${skillKey}」写入组织实例失败`,
      );
    }

    return {
      ok: true,
      successCount,
      failureCount: 0,
      errors: [],
    };
  }

