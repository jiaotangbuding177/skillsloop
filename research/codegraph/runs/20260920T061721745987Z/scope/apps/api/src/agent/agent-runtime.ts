      "goal 用 1 句中文说明能力目标（可稍长），供后续摘要使用；不要与 title 完全相同。",
      "所有字段必须泛化和脱敏，禁止复述姓名、手机号、邮箱、组织名、文件名、路径、网址或业务原文。",
