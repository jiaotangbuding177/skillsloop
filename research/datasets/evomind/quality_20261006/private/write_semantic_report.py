"""把逐条语义审阅结论转成去标识中文说明，不重新推断标签。"""
import json
from pathlib import Path

HERE=Path(__file__).resolve().parent
rows=[json.loads(x) for x in (HERE/'semantic_audit.jsonl').read_text(encoding='utf-8').splitlines()]
support={'supported':'正文支持','partial':'部分支持，需收窄','unsupported':'正文不支持','unclear':'无法判断'}
alignment={'coherent':'对应','partial':'部分对应','unclear':'无法判断','mismatch':'不对应'}
text='''# 候选学习片段：37条正文语义复核

日期：2026-10-06。范围：本轮富化版719个候选中的固定样本。本文件只呈现去标识结论；原文、消息编号和逐字证据保存在同目录下的 `private/semantic_audit.jsonl`。

本轮读完37个候选窗口的全部209条消息正文，共76,685字符。21条候选的可复用方法得到正文支持，16条仅得到部分支持，需要收窄经验范围或保留未完成约束。目标与方法31条对应、6条部分对应。这里的“支持”只回答“这段方法能否从所给正文归纳出来”，不认证它在企业环境实际执行正确，也不认证法律、化学品监管、工商或业务事实。

样本怎么选：候选编号排序后每24条取第1条，共30条；另加入全部8条前轮定向增补，其中1条与前组重叠，所以共37条。8条增补曾由同一审阅者在前轮审过，本轮重新读全文；另外29条为本轮复核。不能用这些结果计算独立标注一致性，也不能把带定向增补的结果当719条总体准确率或召回率。不存在本轮全量人工金标准。

## 口径

| 检查问题 | 本轮怎么判断 | 不能推出什么 |
|---|---|---|
| 可迁移方法有无依据 | 在正文找到步骤、判断条件、修订、失败应对或明确的验收边界 | 正文说“执行了”不等于工具真的执行成功 |
| 方法是否处理用户需求 | 检查用户目标、对象和约束与方法的对应关系 | 相关主题不等于整个会话都是一条完整任务轨迹 |
| 有无修订或失败经验 | 区分用户纠正、助手自述故障、计划性防错和缺证说明 | 建议不能当作历史失败；用户要求修订不能当成修订完成 |
| 结果是否可靠 | 仅核对可见文字内的逻辑与局部计数 | 无附件不意味着方法没有价值，也不能据助手声明验证附件内容 |

“部分支持”不是整个会话无价值。例如正文明确给出字体或解释器修复办法，但候选概括额外加入了未显示的视觉验收、产物完整检查或多文件同步，就应该保留已见方法，缩小尚无证据的部分。

## 逐条结论

以下编号对应冻结样本中的位置，原消息编号不在公开说明复制。所有样本都读了完整候选窗口正文；没有将会话级工具记录错误分配成局部执行回执，也未用外部模型或运行服务验证。

| 样本 | 方法依据 | 需求对应 | 说人话的结论 |
|---|---|---|---|
'''
for r in rows:
    summary=r['readable_assessment'].replace('|','／').replace('\n',' ')
    text+=f"| {r['rank']:02d} | {support[r['method_support']]} | {alignment[r['goal_method_alignment']]} | {summary} |\n"
text+='''
## 值得关注的边界

1. **不要把候选总结写得比正文更完整。** 样本14只显示解释器与pip诊断，尚未显示PDF完整验收；样本26显示富文本修复，尚未显示几何检查。方法本身可保留，附加步骤应标为建议或待验证。
2. **用户纠正与成功落实要分开。** 样本18的最新事实优先要求、样本30的不带入旧月份内容要求，以及样本31的主体名称调整，均不能因用户明确提出，就当助手已正确落实。时间先后尚未认证，更不能强行编成“失败—修复—成功”。
3. **生成与自检声明仍然需要边界。** 样本22承认无法看所给参考图；样本36同时存在漏字、前后字号标准不同与“全部保留”的声明。局部修复办法值得学习，完整交付验收保持未知。
4. **领域方法与具体结论分开。** 样本04的实体消歧、样本13的产品和经营主体区分、样本31的条款对应有方法价值，但工商控制、监管许可、合同违约等结论没有本轮专业认证，不能直接变为确定规则。
5. **保留真实不确定，不把自然缺陷抹平。** 样本09的主题上下文缺失、样本35的审查对象未在用户文字明确，均标“部分对应”。缺失输入和文件不自动否定所有学习片段，但要明确不能验证的部分。

## 字数样本的复核更正

样本01的推荐段声称199字（含标点）。同一可见段，保留空白按Unicode码点计数为232，去空白为230，再排除ASCII字母和数字为199。三个值都可直接复算，但平台究竟采用哪种“字”口径未知。因此最初仅由232／230推为超限的解释不成立，本轮更正为**计数口径未交代，业务限长验收未知**，不认定模型造假、不认定用户200字条件已被违反。

受控证据 `private/character_count_evidence.json` 保存原段、起止边界和三种计算规则；逐条语义标签同时含 `outcome_check`。这只核对可见文字，不验证输出文件或申报平台结果。

## 产物与限制

- `private/sample_selection.json`：冻结选样规则、编号、来源SHA256和读取规模。
- `private/semantic_audit.jsonl`：37条逐条标签、中文结论、75处通过逐字包含校验的消息编号与引文，以及缺证和误迁移风险。
- `private/character_count_evidence.json`：字数例的受控复算材料。
- `private/read_semantic_sample.py`：按冻结规则展开全部候选正文的读取程序。
- `private/write_semantic_audit.py`、`private/write_semantic_report.py`：保存已完成审阅及校验锚点，不执行模型任务、不重新自动决定语义标签。

本轮没有改变原筛选标签、719个候选或历史来源。所有候选实际执行、业务成功和时间顺序都保持未认证。正文支持和部分支持均不能直接拿来计算skills实际增益，后续生成只应使用有来源的方法片段，把待验证条件和未知项一起带入。
'''
(HERE.parent/'semantic_audit.md').write_text(text,encoding='utf-8')
